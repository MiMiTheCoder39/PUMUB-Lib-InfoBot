def localize_notification_title(notification):
    """Translate the event prefix while preserving stored book/person data."""
    if not notification:
        return ""
    get = notification.get if hasattr(notification, "get") else lambda key, default=None: getattr(notification, key, default)
    raw = str(get("title", "") or "")
    ntype = str(get("type", "") or "")
    key = _NOTIFICATION_TITLE_KEYS.get(ntype)
    if not key:
        return raw
    subject = ""
    for separator in ("—", " - ", ":"):
        if separator in raw:
            subject = raw.split(separator, 1)[1].strip()
            break
    prefix = translate(key)
    return f"{prefix} — {subject}" if subject else prefix


def _notification_parts(notification):
    get = notification.get if hasattr(notification, "get") else lambda key, default=None: getattr(notification, key, default)
    raw_title = str(get("title", "") or "")
    raw_message = str(get("message", "") or "")
    ntype = str(get("type", "") or "")
    subject = ""
    if "—" in raw_title:
        subject = raw_title.split("—", 1)[1].strip()
    elif " - " in raw_title:
        subject = raw_title.split(" - ", 1)[1].strip()
    if not subject:
        match = re.search(r'["“](.*?)["”]', raw_message)
        subject = match.group(1).strip() if match else ""
    borrow_id = ""
    match = re.search(r'(?:Borrow ID|ငှားယူ ID|ငှားရမ်းမှုအမှတ်)\s*[:：]?\s*([A-Za-z0-9-]+)', raw_message)
    if match:
        borrow_id = match.group(1)
    due_date = ""
    match = re.search(r'(?:Due Date|ပြန်အပ်ရမည့်ရက်)\s*[:：]?\s*([^\n]+)', raw_message)
    if match:
        due_date = match.group(1).strip()
    days = ""
    match = re.search(r'(?:နောက်ကျသောရက်|နောက်ကျသည့်ရက်|ပြန်အပ်ရန်)\s*[^0-9]*([0-9]+)\s*ရက်', raw_message)
    if match:
        days = match.group(1)
    fine = ""
    match = re.search(r'(?:Fine Amount|ဒဏ်ကြေးပမာဏ|ဒဏ်ငွေ)\s*[:：]?\s*([0-9,]+)\s*MMK', raw_message)
    if match:
        fine = match.group(1)
    return ntype, subject, borrow_id, due_date, days, fine, raw_message


